'use strict';
const fs=require('node:fs');
const {Runner}=require('../lib/runner');
const gateway=require('../lib/gateway');
const c=JSON.parse(fs.readFileSync(process.env.ESB_GATEWAY_VALUES,'utf8'));
const controller=new AbortController();
for(const signal of ['SIGINT','SIGTERM'])process.once(signal,()=>controller.abort());
const r=new Runner({env:process.env,signal:controller.signal,emit:e=>process.stdout.write('[ESB_API] '+JSON.stringify(e)+'\n')});
const action=process.argv[2];
if(!['policy','reconcile'].includes(action))throw Error('Unknown gateway action.');
gateway[action](r,c).catch(e=>{console.error(e.message);process.exitCode=1;});
